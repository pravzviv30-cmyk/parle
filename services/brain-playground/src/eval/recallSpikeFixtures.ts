/**
 * Invented learners and scene requests for the recall spike (recallSpike.ts).
 *
 * Every person, place and detail here is made up for the spike. No real learner.
 *
 * Gold labels were written before the spike was run and are not changed after
 * seeing results. `overlap` cases are scenes whose gold items share obvious
 * words with the scene. `gap` cases are scenes whose gold items relate by
 * meaning only (a move to Lyon and a flat viewing, a sister's wedding and
 * buying a present). Gold is what a good human tutor would want to recall,
 * chosen from any of the learner's facts, patterns and summaries.
 */

export interface Fact { id: string; en: string; fr: string | null }
export interface Pattern { id: string; tag: string; example: string }
export interface Summary { id: string; title: string; summary: string; topics: string[] }
export interface Learner { id: string; facts: Fact[]; patterns: Pattern[]; summaries: Summary[] }
export interface Scene {
  learnerId: string;
  scene: string;
  kind: 'overlap' | 'gap';
  gold: [string, string, string];
}

const f = (id: string, en: string, fr: string | null = null): Fact => ({ id, en, fr });
const p = (id: string, tag: string, example: string): Pattern => ({ id, tag, example });
const s = (id: string, title: string, summary: string, topics: string[]): Summary => ({ id, title, summary, topics });

