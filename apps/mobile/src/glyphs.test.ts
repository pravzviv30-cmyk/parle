/**
 * The glyph set, read as source — F589, F598.
 *
 * There is no renderer in this workspace (docs/TESTING.md), so this is the
 * `motion.test.ts` idiom: walk the files that hold the app's marks, strip the
 * comments, and fail on the shapes that break the one-pen rule. The ceiling is
 * honest: it proves the marks are drawn at one weight and hidden from
 * assistive tech, never that a phone drew a cup.
 *
 * Come alive (founder decision D11) moved every mark into one generated family:
 * `npm run icons` writes `src/icons/<Pascal>.tsx` from Iconsax and Luvani's own
 * drawings, and `glyphs.tsx` and `nav/icons.tsx` became delegates that draw
 * `<Icon name=... />`. So the pen is checked where the drawing now is, in every
 * file the generator wrote, and the two old files are checked to draw nothing
 * of their own.
 *
 * The place map is checked against `packages/core`'s own union rather than a
 * list written here, because a seventh place added to the catalogue with no mark
 * to draw it is exactly the miss this test is for.
 */

import { describe, test } from 'node:test';
import assert from 'node:assert/strict';
import { readdirSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { ICON_NAMES } from './icons/names.ts';
import { PLACE_ICON } from './icons/places.ts';

const read = (relative: string): string => readFileSync(fileURLToPath(new URL(relative, import.meta.url)), 'utf8');

/** Comments may say anything; only what reaches glass is under test. */
function stripComments(source: string): string {
  const noBlocks = source.replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, ' '));
  return noBlocks.replace(/(^|[^:])\/\/.*$/gm, (_m, keep: string) => keep);
}

const FILES = [
  { name: 'glyphs.tsx', body: stripComments(read('./glyphs.tsx')) },
  { name: 'nav/icons.tsx', body: stripComments(read('./nav/icons.tsx')) },
];

const GLYPHS = FILES[0]!.body;

/** Every file `scripts/icons/build-icons.mjs` wrote: the ones whose first line is its header. */
const GENERATED = readdirSync(fileURLToPath(new URL('./icons/', import.meta.url)))
  .filter((file) => file.endsWith('.tsx'))
  .map((file) => ({ name: `icons/${file}`, raw: read(`./icons/${file}`) }))
  .filter(({ raw }) => raw.startsWith('// Generated by scripts/icons/build-icons.mjs'))
  .map(({ name, raw }) => ({ name, body: stripComments(raw) }));

/** Every place a mission can happen in, taken from the catalogue's own union. */
const PLACES: string[] = (() => {
  const missions = read('../../../packages/core/src/missions/missions.ts');
  const at = missions.indexOf('export type MissionPlace');
  assert.notEqual(at, -1, 'MissionPlace has moved out of packages/core/src/missions/missions.ts');
  const union = missions.slice(at, missions.indexOf(';', at));
  return (union.match(/'[a-z]+'/g) ?? []).map((q) => q.slice(1, -1));
})();

describe('one pen drew every mark in the app — F589', () => {
  test('every glyph draws in the one stroke weight and hides from assistive technology', () => {
    assert.ok(PLACES.length >= 6, `the union parsed to ${PLACES.length} places, so the place check below asserts nothing`);
    assert.ok(GENERATED.length >= 90, `only ${GENERATED.length} generated icon files were found, so this walk reads almost nothing`);

    for (const { name, body } of GENERATED) {
      const svgs = body.match(/<Svg[^>]*>/g) ?? [];
      assert.ok(svgs.length > 0, `${name} draws no Svg at all; this test is reading the wrong file`);
      for (const tag of svgs) {
        assert.ok(
          tag.includes('{...decorative}'),
          `${name} draws an Svg a screen reader will announce as an unlabelled image: ${tag}`,
        );
      }

      // One pen: every stroke is theme.ts's STROKE, and every mark that strokes says so.
      for (const weight of body.match(/strokeWidth=\{([^}]*)\}/g) ?? []) {
        assert.equal(weight, 'strokeWidth={STROKE}', `${name} writes its own stroke weight: ${weight}; the app has one pen and it is theme.ts's`);
      }
      const stroked = (body.match(/<\w+ [^>]*stroke=\{(?:color|secondary)\}[^>]*\/?>/g) ?? []).filter((tag) => !tag.startsWith('<Svg') && !tag.startsWith('<G '));
      for (const tag of stroked) {
        assert.ok(tag.includes('strokeWidth={STROKE}'), `${name} strokes a mark at the SVG default of 1: ${tag.slice(0, 80)}`);
      }

      // A mark is coloured by the caller and nothing else: its own colour, the
      // Bulk second layer, or nothing at all, and the second layer's opacity is
      // the one shared number.
      for (const paint of body.match(/\b(?:fill|stroke)=(?:\{[^}]*\}|"[^"]*")/g) ?? []) {
        assert.ok(
          ['fill={color}', 'fill={secondary}', 'fill="none"', 'stroke={color}', 'stroke={secondary}', 'stroke="none"'].includes(paint),
          `${name} paints with something other than the mark's colours: ${paint}`,
        );
      }
      for (const opacity of body.match(/\bopacity=(?:\{[^}]*\}|"[^"]*")/g) ?? []) {
        assert.equal(opacity, 'opacity={SECONDARY_OPACITY}', `${name} sets an opacity of its own: ${opacity}`);
      }
      assert.doesNotMatch(body, /#[0-9a-fA-F]{3,8}\b|rgba?\(|url\(/, `${name} carries a raw colour or a url()`);
    }

    // The two old glyph files draw nothing of their own any more: each mark is
    // the generated one, so there is one pen and one place it is held.
    for (const { name, body } of FILES) {
      assert.doesNotMatch(body, /<Svg\b|strokeWidth=|from 'react-native-svg'/, `${name} draws a mark of its own beside the generated set`);
    }
  });

  test('every place a conversation happens in has a mark of its own', () => {
    const map = PLACE_ICON as Record<string, string>;
    for (const place of PLACES) {
      assert.ok(Object.hasOwn(map, place), `PLACE_ICON has no icon for ${place}, so that row's disc is drawn empty`);
      assert.ok((ICON_NAMES as readonly string[]).includes(map[place]!), `${place} is drawn with ${map[place]}, which is not in the icon set`);
    }
    assert.deepEqual(Object.keys(map).sort(), [...PLACES].sort(), 'PLACE_ICON names a place the catalogue does not have');
    assert.equal(new Set(Object.values(map)).size, PLACES.length, 'two places share one icon, so two rows look like one situation');
    // And the glyph draws through the map, never a default of its own.
    const glyph = GLYPHS.slice(GLYPHS.indexOf('export function PlaceGlyph('), GLYPHS.indexOf('\nexport ', GLYPHS.indexOf('export function PlaceGlyph(') + 1));
    assert.match(glyph, /<Icon name=\{PLACE_ICON\[place\]\}/, 'PlaceGlyph does not draw the icon PLACE_ICON gives its place');
  });

  test('every glyph is an ICONS.md mark at the one stroke weight or a kept drawing on the retire list, and the tab and the control share one microphone', () => {
    // Revamp B, F598. Every revamp A name survives in its file, so no caller
    // moved; where ICONS.md draws the same thing its path replaced the old one.
    // The fourteen after them are the ICONS.md marks the Round 1 boards draw
    // that no older name covered. The list is exact, so a glyph added without
    // being named here, or one lost, fails rather than drifting in.
    const PORTED = ['MouthGlyph', 'ClockGlyph', 'ChatGlyph', 'DocumentGlyph', 'ReplayGlyph', 'WaveformGlyph'];
    const ROUND_ONE = [
      'ChevronDownGlyph',
      'PlayGlyph',
      'SpeakerSlowGlyph',
      'MicOffGlyph',
      'KeyboardGlyph',
      'PlusGlyph',
      'SearchGlyph',
      'SettingsGlyph',
      'LockGlyph',
      'ShareGlyph',
      'CardsGlyph',
      'InfoGlyph',
      'PostcardGlyph',
    ];
    // F601: the alert is one of the fourteen, but `Field` draws it beside its
    // error line, so it is drawn in components.tsx and re-exported here, the
    // way the speaker is. It is pinned as a re-export below, not as a drawing.
    const RE_EXPORTED = ['AlertGlyph'];
    // ICONS.md had no match for these. Since come alive they are delegates to
    // the generated set like the rest, and the names stay until the stage that
    // redraws their callers retires them.
    const KEPT_UNTIL: Record<string, string> = {
      CoffeeCupGlyph: 'Stage 3, with the rows that draw a place disc',
      QuoteGlyph: 'Stage 6, with the phrase shelf row',
      PlaceGlyph: 'Stage 6, once Stage 3 draws the places with the flat illustrations',
    };
    const exported = [...GLYPHS.matchAll(/export function (\w+(?:Glyph|Icon))\b/g)].map((m) => m[1]!).sort();
    assert.deepEqual(
      exported,
      [...PORTED, ...ROUND_ONE, ...Object.keys(KEPT_UNTIL)].sort(),
      'glyphs.tsx draws a glyph that is neither an ICONS.md mark nor on the retire list, or lost one a screen needs',
    );
    assert.equal(
      ROUND_ONE.length + RE_EXPORTED.length,
      14,
      'the Round 1 set is fourteen marks, thirteen drawn here and the alert re-exported; a fifteenth is a port no board asked for',
    );

    // Come alive (D11): each name is a delegate to the generated icon that
    // means the same thing, so a mark that was quietly drawn by hand again, or
    // pointed at another icon, shows up here.
    for (const [glyph, icon] of [
      ['ClockGlyph', 'clock'],
      ['ChatGlyph', 'chat'],
      ['DocumentGlyph', 'book'],
      ['ReplayGlyph', 'replay'],
      ['WaveformGlyph', 'waveform'],
      ['SpeakerSlowGlyph', 'speaker-slow'],
      ['MouthGlyph', 'mouth'],
    ] as const) {
      const at = GLYPHS.indexOf(`export function ${glyph}(`);
      const next = GLYPHS.indexOf('\nexport ', at + 1);
      assert.ok(GLYPHS.slice(at, next === -1 ? undefined : next).includes(`<Icon name="${icon}" size={size} color={color} />`), `${glyph} is not the generated ${icon}`);
    }
    for (const glyph of exported) {
      const at = GLYPHS.indexOf(`export function ${glyph}(`);
      const next = GLYPHS.indexOf('\nexport ', at + 1);
      assert.match(GLYPHS.slice(at, next === -1 ? undefined : next), /return <Icon name=/, `${glyph} draws something other than the generated set`);
    }
    // The slow speaker is the speaker with its outer arc dashed, and nothing else.
    const slow = stripComments(read('./icons/SpeakerSlow.tsx'));
    assert.match(slow, /<Path d="M19 7a7 7 0 0 1 0 10" fill="none" stroke=\{color\} strokeWidth=\{STROKE\} strokeLinecap="round" strokeLinejoin="round" strokeDasharray="2\.6 2\.6" \/>/, 'the slow speaker lost its dashed arc');

    assert.match(
      GLYPHS,
      /export \{ EarGlyph as SpeakerGlyph \} from '\.\/components\.tsx'/,
      'the speaker is drawn a second time instead of being the ear the tutor already speaks through',
    );
    // F601: the alert is the one Field draws, re-exported the same way, so
    // there is one drawing of it and no import cycle between the two files.
    assert.match(
      GLYPHS,
      /export \{ AlertGlyph \} from '\.\/components\.tsx'/,
      'the alert is not re-exported from components.tsx, so a screen cannot reach the mark Field draws',
    );
    assert.doesNotMatch(GLYPHS, /export function AlertGlyph\b/, 'the alert is drawn a second time here beside the one Field draws');
    // ICONS.md: "speak and mic are the same microphone on purpose".
    const icons = FILES[1]!.body;
    assert.match(
      icons,
      /export \{ MicGlyph as TutorIcon \} from '\.\.\/components\.tsx'/,
      'the Speak tab draws its own microphone instead of the one the control draws',
    );
    assert.doesNotMatch(icons, /export function TutorIcon\b/, 'the Speak tab is drawn a second time beside the re-export');
    // The pair of chevrons stays together in components.tsx, beside the back
    // one, and so do close and check: this file imports from that one.
    assert.ok(!/export function ChevronRight\b/.test(GLYPHS), 'glyphs.tsx draws a second right chevron away from ChevronLeft');
    assert.ok(!/export function (Close|Check)Glyph\b/.test(GLYPHS), 'close or check is drawn here, away from the parts that draw them');
  });
});
