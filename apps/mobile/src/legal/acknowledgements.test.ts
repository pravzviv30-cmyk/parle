/**
 * The Acknowledgements screen credits the face the app is set in — F596.
 *
 * Revamp B sets every word in Outfit and takes Fraunces and DM Sans out of the
 * bundle. The OFL lets us embed a font only if its copyright notice and licence
 * travel with it, so the screen has to credit the face that actually ships, and
 * must stop crediting two faces that no longer do. A credit for a font we do
 * not ship is a small lie; a font we ship with no credit is a licence breach.
 *
 * The OFL asks for the licence text to travel with the font, so the licence
 * file has to be in the fonts folder, and the author line has to be the one
 * that file carries rather than one written from memory.
 *
 * Source-read rather than rendered, like the other contract tests here: the
 * failure this exists to catch is a stale string in one file, not a layout.
 */

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { ICON_CONFIG, ICONSAX_VERSION } from '../../../../scripts/icons/icons.config.mjs';
import { pascal } from '../../../../scripts/icons/svg.mjs';

const SCREEN = fileURLToPath(new URL('./Acknowledgements.tsx', import.meta.url));
const OFL_OUTFIT = fileURLToPath(new URL('../../assets/fonts/OFL-Outfit.txt', import.meta.url));
const ICONS = fileURLToPath(new URL('../icons/', import.meta.url));
const ICON_SET = fileURLToPath(new URL('../../../../docs/design-assets/ICON_SET.md', import.meta.url));

test('Acknowledgements credits Outfit under the OFL and names no retired face', () => {
  const source = readFileSync(SCREEN, 'utf8');

  assert.match(source, /name: 'Outfit'/, 'the screen does not credit Outfit, the face every word is set in');
  assert.match(source, /SIL Open Font License 1\.1/, 'the screen does not name the licence Outfit is embedded under');
  assert.doesNotMatch(
    source,
    /Fraunces|DM Sans/,
    'the screen still credits a face the app no longer ships',
  );

  assert.ok(
    existsSync(OFL_OUTFIT),
    'the screen says the licence text ships with the app, and OFL-Outfit.txt is not in assets/fonts',
  );

  // The credit names the authors the licence file names, not a paraphrase.
  const by = source.match(/name: 'Outfit',\s*by: '([^']+)'/);
  assert.ok(by, 'the Outfit notice has no author line next to its name');
  const copyright = readFileSync(OFL_OUTFIT, 'utf8').split('\n')[0] ?? '';
  assert.ok(
    copyright.includes(by[1]!),
    `the Outfit credit says "${by[1]}" but OFL-Outfit.txt says "${copyright}"`,
  );
});

/**
 * The icon set credits its licence — F726.
 *
 * The icons are Iconsax free icons (founder decision D11), used inside the
 * app's source under the Iconsax free licence, which asks for a notice and
 * forbids sharing the icons as loose files. So the screen credits the set, and
 * every file the generator wrote carries the notice in its first line, naming
 * the icon it was drawn from; Luvani's own drawings say so instead. The header
 * is written out here in full rather than read from the generator, so a
 * generator that quietly dropped the notice fails this test.
 */
test('the icon set credits its licence in Acknowledgements', () => {
  const source = readFileSync(SCREEN, 'utf8');
  assert.match(
    source,
    /\{\s*name: 'Iconsax',\s*by: 'Vuesax \(iconsax\.io\)',\s*licence: 'Iconsax Free License',\s*note: 'The icons on buttons, rows and choices, built into the app\. They are not shared as icon files\.',\s*\}/,
    'Acknowledgements does not credit the Iconsax set, its author and its licence',
  );
  // No Iconsax licence text ships with the app, so the screen may not tell the
  // learner that every licence's full text does.
  assert.doesNotMatch(source, /full licence text for each/i, 'the screen says every licence ships in full, and the Iconsax licence text does not ship');

  const generated = readdirSync(ICONS).filter((file) => file.endsWith('.tsx') && readFileSync(`${ICONS}${file}`, 'utf8').startsWith('// Generated by scripts/icons/build-icons.mjs'));
  const config = Object.entries(ICON_CONFIG);
  assert.equal(generated.length, config.length, `${generated.length} generated icon files for ${config.length} icons in the config`);
  let iconsax = 0;
  for (const [name, spec] of config) {
    const file = `${ICONS}${pascal(name)}.tsx`;
    assert.ok(existsSync(file), `${name} has no generated file`);
    const first = readFileSync(file, 'utf8').split('\n', 1)[0];
    const expected =
      spec.source === 'iconsax'
        ? `// Generated by scripts/icons/build-icons.mjs from iconsax@${ICONSAX_VERSION} (${spec.from}). Do not edit by hand. Iconsax icon used inside Luvani's source under the Iconsax free licence (https://docs.iconsax.io/license-and-terms/license); not for redistribution as loose icon files.`
        : `// Generated by scripts/icons/build-icons.mjs from scripts/icons/custom/${spec.from}.svg. Do not edit by hand. Luvani original.`;
    assert.equal(first, expected, `${pascal(name)}.tsx does not open with its notice`);
    if (spec.source === 'iconsax') iconsax += 1;
  }
  assert.ok(iconsax >= 80, `only ${iconsax} icons come from Iconsax, so this is not the set the screen credits`);
  assert.equal(ICONSAX_VERSION, '0.1.1', 'the credited set moved off the pinned iconsax 0.1.1');

  // The register names the licence and the licensee, and says no loose file is kept.
  const register = readFileSync(ICON_SET, 'utf8');
  assert.match(register, /Iconsax free licence/, 'ICON_SET.md does not name the licence');
  assert.match(register, /held by the founder as\s+the individual licensee/, 'ICON_SET.md does not say who holds the licence');
  assert.match(register, /no Iconsax SVG is committed/, 'ICON_SET.md does not say the icons are never kept as loose files');
});
