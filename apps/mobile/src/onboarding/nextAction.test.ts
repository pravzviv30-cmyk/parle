import assert from 'node:assert/strict';
import { test } from 'node:test';
import { readFileSync } from 'node:fs';
import { nextAction } from './nextAction.ts';
test('tapping a disabled Next lifts the choices and says to choose one, never a shake', () => {
  let advances = 0, explanations = 0;
  const advance = () => { advances++; return true; };
  assert.equal(nextAction(true, advance, () => { explanations++; }), false);
  assert.equal(advances, 0);
  assert.equal(explanations, 1);
  assert.equal(nextAction(false, advance, () => { explanations++; }), true);
  assert.equal(advances, 1);
  assert.equal(explanations, 1);
  const next = readFileSync(new URL('./NextButton.tsx', import.meta.url), 'utf8');
  assert.match(next, /nextAction\(disabled, onPress, onDisabledPress\)/);
  assert.match(next, /accessibilityState=\{\{ disabled \}\}/);
  assert.doesNotMatch(next, /disabled=\{disabled\}/, 'the explanatory touch must still arrive');
  const page = readFileSync(new URL('./PreAccountOnboarding.tsx', import.meta.url), 'utf8');
  assert.match(page, /disabled=\{answer == null\}/);
  assert.match(page, /if \(!reduced\) soft\(\)/);
  assert.match(page, /accessibilityLiveRegion="polite"[^>]*>Choose one to continue\./);
  const nudge = readFileSync(new URL('./firstRun/ChoiceNudge.tsx', import.meta.url), 'utf8');
  assert.match(nudge, /useReduceMotion\(\)/);
  assert.match(nudge, /!reduced/);
  assert.match(nudge, /index \* 40/);
  assert.match(nudge, /timing\(-3,/);
  assert.match(nudge, /timing\(0,/);
  assert.match(nudge, /cancel\(y\)/);
  assert.doesNotMatch(nudge, /translateX|shake/);
});
