/**
 * Convert revamp B's flat illustrations into react-native-svg components:
 * `node scripts/illustrations.mjs <path to ILLUSTRATIONS.md>`.
 *
 * ILLUSTRATIONS.md is the illustrator's catalogue: one `### id` per drawing, a
 * line that says where it sits and the size it is displayed at, and the whole
 * `<svg>` to paste. The revamp ships the 47 place, state, celebrate
 * and postcard drawings (nineteen of them places and nineteen postcards) and the six original mouth guides.
 *
 * Each drawing becomes `apps/mobile/src/art/flat/<id>.tsx`, a component that
 * takes a width and a height and returns one decorative `<Svg>`, and
 * `art/flat/index.ts` becomes the one registry: the component, its viewBox and
 * the sizes the catalogue displays it at. Screens draw through
 * `art/flat/Illustration.tsx`, never by importing a drawing.
 *
 * The conversion is strict on purpose. Every colour goes through one map to a
 * palette token, so `palette.ts` stays the only file in the app with a raw hex,
 * and an element, an attribute or a hex this map does not know is a hard
 * failure: a new drawing cannot smuggle a colour, a gradient, a filter or a
 * word in without somebody deciding to let it. A stale generated file (one
 * whose drawing left the catalogue) is removed; a hand-written file in the
 * folder carries no generated header and is never touched.
 *
 * Deterministic and idempotent: the output depends on the catalogue alone, and
 * a file whose content would not change is not rewritten, so running it twice
 * leaves `git status` clean.
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'apps', 'mobile', 'src', 'art', 'flat');

/** Drawings that wait for a later round. */


/** The first line of every generated file, so a generated file is recognisable. */
const header = (id) => `// Generated by scripts/illustrations.mjs from ILLUSTRATIONS.md (${id}). Do not edit by hand.`;
const INDEX_HEADER = '// Generated by scripts/illustrations.mjs from ILLUSTRATIONS.md. Do not edit by hand.';

/** SVG element to react-native-svg component. Nothing else is drawn. */
const ELEMENTS = { rect: 'Rect', circle: 'Circle', ellipse: 'Ellipse', path: 'Path', polygon: 'Polygon', g: 'G' };

/** Attributes that are numbers, written as `{n}`. */
const NUMBERS = new Set(['x', 'y', 'width', 'height', 'rx', 'ry', 'cx', 'cy', 'r', 'stroke-width', 'stroke-opacity']);
/** Attributes that stay strings, written as `"s"`. `transform` is kept as SVG's own string. */
const STRINGS = new Set(['d', 'points', 'transform', 'stroke-linecap', 'stroke-linejoin', 'stroke-dasharray', 'fill-rule']);
/** Attributes that carry a colour, written as a token or `"none"`. */
const COLOURS = new Set(['fill', 'stroke']);

/** Every hex the catalogue may use, and the one palette token it is. */
const HEX = {
  '#16123A': 'paper.ink',
  '#FFFFFF': 'paper.card',
  '#FFF6E9': 'paper.ground',
  '#EADFCB': 'paper.line',
  '#FFC93C': 'colour.sun',
  '#2FD18B': 'colour.mint',
  '#D63A22': 'colour.coral',
  '#3B2FE0': 'colour.blue',
  '#B9A7FF': 'lilac',
};

/** The outer `<svg>`: what is kept, and what is dropped because the component supplies it. */
const OUTER_KEPT = new Set(['viewBox', 'fill']);
const OUTER_DROPPED = new Set(['width', 'height', 'aria-hidden']);

function fail(id, message) {
  console.error(`illustrations: ${id}: ${message}`);
  process.exit(1);
}

const camel = (name) => name.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const pascal = (id) => id.split('-').map((part) => part[0].toUpperCase() + part.slice(1)).join('');

/** `a="1" b="x"` to ordered pairs; anything that is not a plain quoted attribute fails. */
function attributes(id, source) {
  const pairs = [];
  const rest = source.replace(/([a-zA-Z:-]+)="([^"]*)"/g, (_, name, value) => {
    pairs.push([name, value]);
    return '';
  });
  if (rest.trim() !== '') fail(id, `unreadable attributes: ${source.trim()}`);
  return pairs;
}

function number(id, name, value) {
  const n = Number(value);
  if (value.trim() === '' || !Number.isFinite(n)) fail(id, `${name}="${value}" is not a number`);
  return String(n);
}

/** One attribute as JSX, and the token root it needs imported, if any. */
function attribute(id, element, name, value, used) {
  const prop = camel(name);
  if (NUMBERS.has(name)) return `${prop}={${number(id, name, value)}}`;
  if (STRINGS.has(name)) {
    if (/["{}<>]/.test(value)) fail(id, `${element} ${name} carries a character JSX cannot hold: ${value}`);
    return `${prop}="${value}"`;
  }
  if (COLOURS.has(name)) {
    if (value === 'none') return `${prop}="none"`;
    const token = HEX[value.toUpperCase()];
    if (token === undefined) fail(id, `${element} ${name}="${value}" is not a palette colour; add it to palette.ts and to the map in this script, or redraw it`);
    used.add(token.split('.')[0]);
    return `${prop}={${token}}`;
  }
  return fail(id, `${element} carries an attribute this script does not know: ${name}="${value}"`);
}

/** The `<svg>` markup to a component body, the viewBox, and what it imports. */
function convert(id, svg) {
  const open = /^<svg\b([^>]*)>/.exec(svg);
  if (!open) fail(id, 'no <svg> opens the drawing');
  if (!svg.endsWith('</svg>')) fail(id, 'the drawing does not close its <svg>');

  let viewBox = null;
  let outerFill = null;
  for (const [name, value] of attributes(id, open[1])) {
    if (OUTER_DROPPED.has(name)) continue;
    if (!OUTER_KEPT.has(name)) fail(id, `the <svg> carries an attribute this script does not know: ${name}`);
    if (name === 'viewBox') viewBox = value;
    if (name === 'fill') outerFill = value;
  }
  if (outerFill !== 'none') fail(id, `the <svg> fill is "${outerFill}", not "none"`);
  const box = /^0 0 (\d+(?:\.\d+)?) (\d+(?:\.\d+)?)$/.exec(viewBox ?? '');
  if (!box) fail(id, `the viewBox "${viewBox}" does not start at 0 0`);

  const body = svg.slice(open[0].length, svg.length - '</svg>'.length);
  const components = new Set();
  const tokens = new Set();
  const lines = [];
  const stack = [];
  let at = 0;
  for (const tag of body.matchAll(/<(\/?)([a-zA-Z]+)((?:\s+[a-zA-Z:-]+="[^"]*")*)\s*(\/?)>/g)) {
    const between = body.slice(at, tag.index);
    if (between.trim() !== '') fail(id, `text or markup this script cannot read: ${between.trim().slice(0, 60)}`);
    at = tag.index + tag[0].length;
    const [, closing, element, attrs, selfClosing] = tag;
    const component = ELEMENTS[element];
    if (component === undefined) fail(id, `an element this script does not draw: <${element}>`);
    const indent = '      ' + '  '.repeat(stack.length);
    if (closing) {
      if (stack.pop() !== element) fail(id, `</${element}> closes nothing it opened`);
      lines.push(`${'      ' + '  '.repeat(stack.length)}</${component}>`);
      continue;
    }
    components.add(component);
    const props = attributes(id, attrs).map(([name, value]) => attribute(id, element, name, value, tokens));
    const opening = [component, ...props].join(' ');
    if (selfClosing) {
      lines.push(`${indent}<${opening} />`);
    } else {
      if (element !== 'g') fail(id, `<${element}> has children; only a <g> may group`);
      lines.push(`${indent}<${opening}>`);
      stack.push(element);
    }
  }
  if (body.slice(at).trim() !== '') fail(id, `text or markup this script cannot read: ${body.slice(at).trim().slice(0, 60)}`);
  if (stack.length > 0) fail(id, `<${stack.at(-1)}> is never closed`);
  if (lines.length === 0) fail(id, 'the drawing draws nothing');

  return { lines, components, tokens, box: [Number(box[1]), Number(box[2])], viewBox };
}

/** "Display at 350 by 220 on a colour card, or 262 by 165 as a hero spot." */
function sizes(id, text) {
  const display = /Display at (\d+) by (\d+)([^.\n]*)/.exec(text);
  if (!display) fail(id, 'no "Display at W by H" line');
  const small = /, or (\d+) by (\d+)/.exec(display[3]);
  return {
    large: [Number(display[1]), Number(display[2])],
    small: small ? [Number(small[1]), Number(small[2])] : undefined,
  };
}

function drawingFile(id, name, drawing) {
  const svgImports = ['Svg', ...[...drawing.components].sort()];
  const themeImports = ['decorative', ...[...drawing.tokens]].sort();
  return [
    header(id),
    `import ${svgImports[0]}, { ${[...svgImports.slice(1), 'type NumberProp'].join(', ')} } from 'react-native-svg';`,
    `import { ${themeImports.join(', ')} } from '../../theme.ts';`,
    '',
    `export function ${name}({ width, height }: { width: NumberProp; height: NumberProp }) {`,
    '  return (',
    `    <Svg width={width} height={height} viewBox="${drawing.viewBox}" fill="none" {...decorative}>`,
    ...drawing.lines,
    '    </Svg>',
    '  );',
    '}',
    '',
  ].join('\n');
}

const pair = (size) => `[${size[0]}, ${size[1]}]`;

function indexFile(entries) {
  return [
    INDEX_HEADER,
    '//',
    '// The flat illustrations of revamp B, Round 1: the place, state, celebrate and',
    '// postcard drawings from ILLUSTRATIONS.md. `box` is a drawing\'s viewBox;',
    '// `large` and `small` are the sizes the catalogue displays it at. Draw one',
    '// through `Illustration.tsx`, which picks the size, never by importing it.',
    '',
    "import type { ReactElement } from 'react';",
    "import type { NumberProp } from 'react-native-svg';",
    '',
    ...entries.map(({ id, name }) => `import { ${name} } from './${id}.tsx';`),
    '',
    '/** One drawing: the component, its viewBox, and the sizes the catalogue displays it at. */',
    'export type IllustrationEntry = {',
    '  readonly draw: (size: { width: NumberProp; height: NumberProp }) => ReactElement;',
    '  readonly box: readonly [number, number];',
    '  readonly large: readonly [number, number];',
    '  readonly small?: readonly [number, number];',
    '};',
    '',
    'export const ILLUSTRATIONS = {',
    ...entries.map(
      ({ id, name, box, large, small }) =>
        `  '${id}': { draw: ${name}, box: ${pair(box)}, large: ${pair(large)}${small ? `, small: ${pair(small)}` : ''} },`,
    ),
    '} as const satisfies Record<string, IllustrationEntry>;',
    '',
    'export type IllustrationName = keyof typeof ILLUSTRATIONS;',
    '',
  ].join('\n');
}

/** Write only what changed, so a second run touches nothing. */
function write(path, content) {
  if (existsSync(path) && readFileSync(path, 'utf8') === content) return false;
  writeFileSync(path, content);
  return true;
}

function main() {
  const source = process.argv[2];
  if (!source) {
    console.error('usage: node scripts/illustrations.mjs <path to ILLUSTRATIONS.md>');
    process.exit(2);
  }
  const catalogue = readFileSync(source, 'utf8');
  const entries = [];
  for (const section of catalogue.split(/^### /m).slice(1)) {
    const id = section.slice(0, section.indexOf('\n')).trim();
    if (!/^[a-z][a-z0-9-]*$/.test(id)) fail(id, 'an id that is not lower-case words joined by hyphens');
    const svg = /```html\s*\n(<svg[\s\S]*?<\/svg>)\s*\n```/.exec(section);
    if (!svg) fail(id, 'no ```html block holding one <svg>');
    const drawing = convert(id, svg[1]);
    const { large, small } = sizes(id, section.slice(0, svg.index));
    entries.push({ id, name: pascal(id), drawing, box: drawing.box, large, small });
  }
  if (entries.length === 0) fail(source, 'no drawings found');
  const names = new Set(entries.map((e) => e.name));
  if (names.size !== entries.length) fail(source, 'two ids make the same component name');

  mkdirSync(OUT, { recursive: true });
  let changed = 0;
  const produced = new Set(['index.ts']);
  for (const entry of entries) {
    const file = `${entry.id}.tsx`;
    produced.add(file);
    if (write(join(OUT, file), drawingFile(entry.id, entry.name, entry.drawing))) changed += 1;
  }
  if (write(join(OUT, 'index.ts'), indexFile(entries))) changed += 1;

  // A generated drawing whose id left the catalogue goes with it.
  let removed = 0;
  for (const file of readdirSync(OUT)) {
    if (produced.has(file) || !file.endsWith('.tsx')) continue;
    const first = readFileSync(join(OUT, file), 'utf8').split('\n', 1)[0];
    if (first.startsWith('// Generated by scripts/illustrations.mjs')) {
      unlinkSync(join(OUT, file));
      removed += 1;
    }
  }

  console.log(`illustrations: ${entries.length} drawings, ${changed} file(s) written, ${removed} removed.`);
}

main();
