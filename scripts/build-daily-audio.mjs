/** Build-time only. Apache-2.0 Kokoro model, ff_siwis French voice.
 * LUVANI_AUDIO_PYTHON=/path/to/venv/bin/python node --experimental-strip-types scripts/build-daily-audio.mjs
 * Requires kokoro==0.9.4, espeakng-loader==0.2.4 and ffmpeg.
 * Downloads public model weights once. No API key or paid service.
 */
import { spawn } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { DAILY_WORDS } from '../packages/core/src/daily/words.ts';
import { DAILY_PHRASES } from '../packages/core/src/daily/phrases.ts';
const root = resolve(import.meta.dirname, '..');
const dir = resolve(root, 'apps/mobile/assets/daily-kokoro');
mkdirSync(dir, { recursive: true });
const lines = [...DAILY_WORDS.map(w => [w.id,w.fr]), ...DAILY_WORDS.map(w => [w.id+':example',w.exampleFr]), ...DAILY_PHRASES.map(p => [p.id,p.fr])];
const jobs = lines.map(([id,text]) => ({id,text,file:createHash('sha256').update(`Kokoro-82M-v1:ff_siwis:1:${text}`).digest('hex').slice(0,20)+'.m4a'}));
const unique = [...new Map(jobs.map(job => [job.file, job])).values()];
await Promise.all([0,1].map(part => new Promise((resolveJob,reject) => {
  const child = spawn(process.env.LUVANI_AUDIO_PYTHON ?? 'python3', [resolve(root,'scripts/daily-audio-worker.py'),dir], {stdio:['pipe','inherit','inherit']});
  child.on('error',reject); child.on('exit',code => code===0 ? resolveJob() : reject(new Error('Audio generation failed; manifest unchanged.')));
  child.stdin.end(JSON.stringify(unique.filter((_,i)=>i%2===part)));
})));
writeFileSync(resolve(root,'apps/mobile/src/daily/audioManifest.ts'),`// Generated by scripts/build-daily-audio.mjs. Offline Kokoro ff_siwis recordings.\nexport const DAILY_AUDIO: Readonly<Record<string, number>> = {\n${jobs.map(j=>`  ${JSON.stringify(j.id)}: require('../../assets/daily-kokoro/${j.file}'),`).join('\n')}\n};\n`);
console.log(`Validated ${jobs.length} entry recordings.`);
