/** Mechanical upstream licence copy; the generated strings ship in the JS bundle. */
import { readFileSync, writeFileSync } from 'node:fs';
const url = 'https://raw.githubusercontent.com/hexgrad/kokoro/main/LICENSE';
const response = await fetch(url);
if (!response.ok) throw new Error(`Licence fetch failed: ${response.status}`);
const apache = await response.text();
if (!apache.includes('Apache License') || !apache.includes('Version 2.0')) throw new Error('Unexpected upstream licence');
const mit = readFileSync(new URL('../node_modules/toqr/LICENSE.md', import.meta.url), 'utf8');
const output = new URL('../apps/mobile/src/legal/dailyLicences.ts', import.meta.url);
writeFileSync(output, `// Upstream licence copies. Generated by scripts/build-daily-licences.mjs.\nexport const DAILY_LICENCES = ${JSON.stringify([{name:'Kokoro',source:url,text:apache},{name:'toqr',source:'https://github.com/kitten/toqr',text:mit}],null,2)} as const;\n`);
