/**
 * Shared by scripts/sfx/generate.mjs and apps/mobile/src/sound/sfxAssets.test.ts, so the
 * generator and the test agree on what an approval is and on the exact text of the
 * generated apps/mobile/src/sound/sfxManifest.ts. No file I/O here.
 */
import { createHash } from 'node:crypto';

/** @param {Uint8Array | string} bytes */
export const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');

/** The largest a shipped sound file may be. */
export const MAX_M4A_BYTES = 30 * 1024;

/**
 * @typedef {{ id: string, durationMs: number, peakDbfs: number, momentaryMaxLufs: number | null,
 *   wavSha256: string, m4aSha256: string, m4aBytes: number }} SoundEntry
 * @typedef {{ on: string, wavSha256: string }} Approval
 */

/**
 * An approval counts only for the exact synthesis the founder heard: a dated record whose
 * wavSha256 is the sound's current wavSha256. A changed recipe is silent until heard again.
 * @param {readonly { id: string, wavSha256: string }[]} sounds
 * @param {Record<string, unknown>} approvals the parsed scripts/sfx/approvals.json
 * @returns {Record<string, boolean>}
 */
export function approvedFlags(sounds, approvals) {
  const known = new Set(sounds.map((sound) => sound.id));
  for (const id of Object.keys(approvals)) {
    if (!known.has(id)) throw new Error(`approvals.json names "${id}", which is not a sound`);
  }
  /** @type {Record<string, boolean>} */
  const flags = {};
  for (const sound of sounds) {
    const record = /** @type {Partial<Approval> | undefined} */ (approvals[sound.id]);
    flags[sound.id] = Boolean(
      record &&
        typeof record.on === 'string' &&
        /^\d{4}-\d{2}-\d{2}$/.test(record.on) &&
        record.wavSha256 === sound.wavSha256,
    );
  }
  return flags;
}

/** @param {string} id */
const key = (id) => (/^[a-z][a-zA-Z0-9]*$/.test(id) ? id : `'${id}'`);

/**
 * The exact text of apps/mobile/src/sound/sfxManifest.ts.
 * @param {readonly { id: string, durationMs: number }[]} sounds
 * @param {Record<string, boolean>} approved
 */
export function renderSfxManifestTs(sounds, approved) {
  const lines = [
    '// Generated by scripts/sfx/generate.mjs from scripts/sfx/recipes.mjs and scripts/sfx/approvals.json.',
    '// Do not edit by hand: sound/sfxAssets.test.ts rebuilds this text and fails on any difference.',
    "import type { SfxId } from './sfxIds.ts';",
    '',
    '/** Every sound effect, in the order of the recipes table. */',
    `export const SFX_IDS: readonly SfxId[] = [${sounds.map((sound) => `'${sound.id}'`).join(', ')}];`,
    '',
    '/** How long each sound lasts, in milliseconds, as synthesised. */',
    'export const SFX_DURATION_MS: Readonly<Record<SfxId, number>> = {',
    ...sounds.map((sound) => `  ${key(sound.id)}: ${sound.durationMs},`),
    '};',
    '',
    '/**',
    ' * True only for a sound the founder approved by ear, and only while its synthesis is the one',
    ' * they heard (the wavSha256 in approvals.json matches). Anything false must stay silent.',
    ' */',
    'export const SFX_APPROVED: Readonly<Record<SfxId, boolean>> = {',
    ...sounds.map((sound) => `  ${key(sound.id)}: ${approved[sound.id] === true},`),
    '};',
    '',
  ];
  return lines.join('\n');
}
