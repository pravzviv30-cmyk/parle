/**
 * Generate the app's icon set: `npm run icons`.
 *
 *   npm run icons                    write what changed, remove what left the config
 *   npm run icons -- --check         change nothing; exit 1 if anything would change
 *   npm run icons -- --check-names   step 0 alone: every source name exists, nothing else
 *
 * Reads `icons.config.mjs` (the one map from a semantic name to its source) and
 * draws from the pinned `iconsax` devDependency's data (founder decision D11)
 * or from Luvani's own drawings in `custom/`. Writes, in the conventions of
 * `scripts/illustrations.mjs`:
 *
 *   apps/mobile/src/icons/<Pascal>.tsx   one component per icon, with a notice header
 *   apps/mobile/src/icons/index.ts       the ICONS registry, read only by icons/Icon.tsx
 *   apps/mobile/src/icons/names.ts       IconName, BulkIconName, ICON_NAMES
 *   docs/design-assets/ICON_SET.md       one row per icon: source, variants, licence, use
 *   scripts/icons/icons.lock.json        per icon and variant, the source and output hashes
 *
 * The Iconsax free licence allows its icons inside an app's source with a
 * notice and forbids sharing them as loose files, so a raw Iconsax SVG is
 * never written anywhere: it is read from node_modules, cleaned in memory and
 * only the component is kept. Every generated icon file carries the notice.
 *
 * Strict, deterministic and idempotent: the output depends on the config, the
 * pinned package and `custom/` alone; a file whose content would not change is
 * not rewritten; a generated file whose icon left the config is removed; a
 * hand-written file in `icons/` has no generated header and is never touched.
 */

import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ICON_CONFIG, ICONSAX_VERSION } from './icons.config.mjs';
import { ELEMENTS, IconError, clean, parseSvg, pascal, toTsx } from './svg.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..', '..');
const OUT = join(ROOT, 'apps', 'mobile', 'src', 'icons');
const DOC = join(ROOT, 'docs', 'design-assets', 'ICON_SET.md');
const LOCK = join(HERE, 'icons.lock.json');
const CUSTOM = join(HERE, 'custom');

/** The first words of every file this script writes, so a generated file is recognisable. */
const GENERATED = '// Generated by scripts/icons/build-icons.mjs';
const CONFIG_HEADER = `${GENERATED} from scripts/icons/icons.config.mjs. Do not edit by hand.`;

/** The notice every Iconsax-drawn file opens with (docs/come-alive/icons-layout.md 1.2). */
const iconsaxHeader = (from) =>
  `${GENERATED} from iconsax@${ICONSAX_VERSION} (${from}). Do not edit by hand. Iconsax icon used inside Luvani's source under the Iconsax free licence (https://docs.iconsax.io/license-and-terms/license); not for redistribution as loose icon files.`;
/** The header of a file drawn from one of Luvani's own drawings. */
const luvaniHeader = (from) => `${GENERATED} from scripts/icons/custom/${from}.svg. Do not edit by hand. Luvani original.`;

const sha256 = (text) => createHash('sha256').update(text).digest('hex');

/**
 * Component names an icon may not take: the react-native-svg elements a
 * generated file imports beside its own export, and the hand-written parts of
 * `icons/`. An icon called `path` would export `Path` over the element.
 */
const RESERVED = new Set(['Svg', ...Object.values(ELEMENTS), 'Icon', 'IconPart', 'IconTile', 'GoalDial', 'AnimatedIcon', 'Drawing', 'Index', 'Names', 'Places', 'IconMotion']);

function die(message) {
  console.error(`icons: ${message}`);
  process.exit(1);
}

// ------------------------------------------------------------ the source package

function iconsax() {
  let manifestPath;
  try {
    manifestPath = createRequire(import.meta.url).resolve('iconsax/manifest.json');
  } catch {
    die(`iconsax is not installed; run npm ci (it is a root devDependency pinned at ${ICONSAX_VERSION})`);
  }
  const dist = dirname(manifestPath);
  const pkg = JSON.parse(readFileSync(join(dist, '..', 'package.json'), 'utf8'));
  if (pkg.version !== ICONSAX_VERSION) die(`iconsax ${pkg.version} is installed, and the set is pinned to ${ICONSAX_VERSION}`);
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
  const categories = new Map();
  return {
    manifest,
    /** The raw SVG string for one icon and style. Never written to disk. */
    svg(name, style) {
      const entry = manifest[name];
      if (!categories.has(entry.category)) {
        categories.set(entry.category, JSON.parse(readFileSync(join(dist, 'data', `${entry.category}.json`), 'utf8')));
      }
      const svg = categories.get(entry.category)[name]?.[style];
      if (typeof svg !== 'string') die(`iconsax ${name} has no ${style} drawing in its data`);
      return svg;
    },
  };
}

// --------------------------------------------------------------- step 0: names

/** Every source the config names exists, in every variant asked for. Returns the problems. */
function checkNames(source) {
  const problems = [];
  const keys = Object.keys(ICON_CONFIG);
  const sorted = [...keys].sort();
  if (keys.join('\n') !== sorted.join('\n')) problems.push('icons.config.mjs is not sorted by key');
  for (const [name, spec] of Object.entries(ICON_CONFIG)) {
    if (!/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/.test(name)) problems.push(`${name}: not lower-case words joined by hyphens`);
    if (!spec.variants.includes('linear')) problems.push(`${name}: every icon has a Linear drawing`);
    if (spec.variants.some((v) => v !== 'linear' && v !== 'bulk')) problems.push(`${name}: a variant other than linear or bulk`);
    if (spec.source === 'iconsax') {
      const entry = source.manifest[spec.from];
      if (entry === undefined) {
        problems.push(`${name}: iconsax@${ICONSAX_VERSION} has no icon named "${spec.from}"`);
        continue;
      }
      for (const variant of spec.variants) {
        if (!entry.styles.includes(variant)) problems.push(`${name}: iconsax "${spec.from}" has no ${variant} style`);
      }
    } else if (spec.source === 'luvani') {
      for (const variant of spec.variants) {
        const file = join(CUSTOM, variant === 'linear' ? `${spec.from}.svg` : `${spec.from}.${variant}.svg`);
        if (!existsSync(file)) problems.push(`${name}: ${relative(ROOT, file)} is missing`);
      }
    } else problems.push(`${name}: an unknown source "${spec.source}"`);
  }
  const components = new Map();
  for (const name of keys) {
    const component = pascal(name);
    if (components.has(component)) problems.push(`${name} and ${components.get(component)} make the same component name`);
    if (RESERVED.has(component)) problems.push(`${name} makes the component ${component}, which a generated file or icons/ already uses for something else`);
    components.set(component, name);
  }
  return problems;
}

// ------------------------------------------------------------------- the files

function rawSvg(source, spec, variant) {
  if (spec.source === 'iconsax') return source.svg(spec.from, variant);
  return readFileSync(join(CUSTOM, variant === 'linear' ? `${spec.from}.svg` : `${spec.from}.${variant}.svg`), 'utf8');
}

function namesFile(entries) {
  const names = entries.map(([name]) => name);
  const bulk = entries.filter(([, spec]) => spec.variants.includes('bulk')).map(([name]) => name);
  const union = (list) => list.map((n) => `  | '${n}'`).join('\n');
  return [
    CONFIG_HEADER,
    '//',
    '// Every icon a screen may ask for by name. `BulkIconName` is the subset with a',
    '// Bulk drawing, the only ones an `IconTile` or a focused tab may draw.',
    '',
    'export type IconName =',
    `${union(names)};`,
    '',
    'export type BulkIconName =',
    `${union(bulk)};`,
    '',
    'export const ICON_NAMES: readonly IconName[] = [',
    ...names.map((n) => `  '${n}',`),
    '];',
    '',
  ].join('\n');
}

function indexFile(entries) {
  return [
    CONFIG_HEADER,
    '//',
    '// The registry. `icons/Icon.tsx` is its only reader: a screen draws an icon',
    '// through `<Icon name=... />`, never by importing a drawing.',
    '',
    "import type { IconDrawings } from './drawing.ts';",
    "import type { IconName } from './names.ts';",
    ...entries.map(([name]) => `import { ${pascal(name)} } from './${pascal(name)}.tsx';`),
    '',
    'export const ICONS: Readonly<Record<IconName, IconDrawings>> = {',
    ...entries.map(([name]) => `  '${name}': ${pascal(name)},`),
    '};',
    '',
  ].join('\n');
}

function docFile(entries) {
  const variants = (spec) => spec.variants.map((v) => (v === 'linear' ? 'Linear' : 'Bulk')).join(', ');
  const from = (spec) => (spec.source === 'iconsax' ? `Iconsax \`${spec.from}\`` : `Luvani \`custom/${spec.from}.svg\``);
  const licence = (spec) => (spec.source === 'iconsax' ? 'Iconsax free licence' : 'Luvani original');
  const iconsaxCount = entries.filter(([, spec]) => spec.source === 'iconsax').length;
  return [
    '<!-- Generated by scripts/icons/build-icons.mjs from scripts/icons/icons.config.mjs. Do not edit by hand. -->',
    '',
    '# The icon set',
    '',
    `${entries.length} icons, ${iconsaxCount} drawn from iconsax@${ICONSAX_VERSION} and ${entries.length - iconsaxCount} of Luvani's own.`,
    '`npm run icons` generates one component per icon into `apps/mobile/src/icons/`;',
    '`npm run icons -- --check` fails when anything here would change. Screens draw',
    'them by name through `<Icon name="..." />`.',
    '',
    'Linear is for controls and Bulk for tiles, tabs and states. Every stroke is',
    "drawn at the app's one pen, `STROKE` (2), and every icon is decorative: the",
    'control around it says what it does.',
    '',
    'Iconsax icons are used inside the app under the Iconsax free licence',
    '(https://docs.iconsax.io/license-and-terms/license), held by the founder as',
    'the individual licensee. The licence allows them inside source code with a',
    'notice and forbids sharing them as loose files, so no Iconsax SVG is committed:',
    'the generator reads the pinned package, and each generated file carries the',
    'notice in its first line. Acknowledgements credits the set in the app.',
    '',
    '| Name | Source | Variants | Licence | Used for |',
    '|---|---|---|---|---|',
    ...entries.map(([name, spec]) => `| \`${name}\` | ${from(spec)} | ${variants(spec)} | ${licence(spec)} | ${spec.use} |`),
    '',
  ].join('\n');
}

/** Everything the config makes, keyed by absolute path, plus the lock. */
function build(source) {
  const entries = Object.entries(ICON_CONFIG);
  /** @type {Map<string, string>} */
  const files = new Map();
  const lock = { package: `iconsax@${ICONSAX_VERSION}`, icons: {} };
  for (const [name, spec] of entries) {
    const drawings = {};
    const hashes = {};
    for (const variant of spec.variants) {
      const raw = rawSvg(source, spec, variant);
      hashes[variant] = sha256(raw);
      const where = `${name} (${spec.source} ${spec.from}, ${variant})`;
      drawings[variant] = clean(parseSvg(raw, where), where, {
        rotate: spec.rotate,
        translate: spec.translate?.[variant],
        parts: spec.parts?.[variant],
      });
    }
    for (const variant of Object.keys(spec.parts ?? {})) {
      if (!spec.variants.includes(variant)) throw new IconError(`${name}: parts are given for ${variant}, which it does not draw`);
    }
    const header = spec.source === 'iconsax' ? iconsaxHeader(spec.from) : luvaniHeader(spec.from);
    const tsx = toTsx({ name, header, drawings });
    files.set(join(OUT, `${pascal(name)}.tsx`), tsx);
    lock.icons[name] = {
      source: spec.source === 'iconsax' ? `iconsax@${ICONSAX_VERSION}` : 'luvani',
      from: spec.from,
      variants: hashes,
      tsx: sha256(tsx),
    };
  }
  files.set(join(OUT, 'names.ts'), namesFile(entries));
  files.set(join(OUT, 'index.ts'), indexFile(entries));
  files.set(DOC, docFile(entries));
  files.set(LOCK, `${JSON.stringify(lock, null, 2)}\n`);
  return files;
}

/** Generated files in icons/ that the config no longer makes. */
function stale(files) {
  if (!existsSync(OUT)) return [];
  const out = [];
  for (const file of readdirSync(OUT)) {
    const path = join(OUT, file);
    if (files.has(path) || !/\.tsx?$/.test(file)) continue;
    const first = readFileSync(path, 'utf8').split('\n', 1)[0] ?? '';
    if (first.startsWith(GENERATED)) out.push(path);
  }
  return out;
}

/** A hand-written file in icons/ that a generated component would overwrite. */
function collisions(files) {
  const out = [];
  for (const path of files.keys()) {
    if (!path.startsWith(OUT) || !existsSync(path)) continue;
    const first = readFileSync(path, 'utf8').split('\n', 1)[0] ?? '';
    if (!first.startsWith(GENERATED)) out.push(relative(ROOT, path));
  }
  return out;
}

function main() {
  const args = new Set(process.argv.slice(2));
  for (const arg of args) if (!['--check', '--check-names'].includes(arg)) die(`unknown argument ${arg}`);
  const source = iconsax();

  // Step 0, before anything is drawn: every name resolves.
  const problems = checkNames(source);
  if (problems.length > 0) die(`${problems.length} name problem(s):\n  ${problems.join('\n  ')}`);
  if (args.has('--check-names')) {
    console.log(`icons: all ${Object.keys(ICON_CONFIG).length} names resolve in iconsax@${ICONSAX_VERSION} or custom/.`);
    return;
  }

  let files;
  try {
    files = build(source);
  } catch (error) {
    if (error instanceof IconError) die(error.message);
    throw error;
  }
  const clashes = collisions(files);
  if (clashes.length > 0) die(`a generated icon would overwrite a hand-written file: ${clashes.join(', ')}`);

  const changed = [...files].filter(([path, content]) => !existsSync(path) || readFileSync(path, 'utf8') !== content).map(([path]) => path);
  const old = stale(files);
  const count = Object.keys(ICON_CONFIG).length;

  if (args.has('--check')) {
    if (changed.length > 0 || old.length > 0) {
      const lines = [...changed.map((p) => `would write ${relative(ROOT, p)}`), ...old.map((p) => `would remove ${relative(ROOT, p)}`)];
      die(`the generated set has drifted from icons.config.mjs; run npm run icons:\n  ${lines.join('\n  ')}`);
    }
    console.log(`icons: ${count} icons, generated set is current.`);
    return;
  }

  mkdirSync(OUT, { recursive: true });
  mkdirSync(dirname(DOC), { recursive: true });
  for (const path of changed) writeFileSync(path, /** @type {string} */ (files.get(path)));
  for (const path of old) unlinkSync(path);
  console.log(`icons: ${count} icons, ${changed.length} file(s) written, ${old.length} removed.`);
}

main();
