/**
 * The word of the day pool.
 *
 * Home opens on one French word, and which word it is comes from `dailyPick`.
 * That means this file is the whole content surface: there is no generator, no
 * model call and no stored choice, so a word a learner meets on a Tuesday is
 * a word somebody wrote on purpose.
 *
 * What belongs here is the everyday French of the situations this app already
 * teaches: a café, a market, the métro, a hotel desk, a friend's kitchen. Not
 * a frequency list, not vocabulary for its own sake. If a beginner would not
 * hear it in their first week in France, it is the wrong word for this card.
 *
 * Four rules hold the pool together, and three of them are enforced by
 * `daily.test.ts` rather than by good intentions:
 *
 * - **Ids are permanent.** They are never reused and never renumbered, because
 *   a bookmark saved into My French points at one, and re-pointing it would
 *   quietly change what a learner saved.
 * - **No digits anywhere a learner reads.** A number on this card is either a
 *   price that is already wrong or a count that means nothing, and PEDAGOGY.md
 *   keeps counts off the surfaces meant to be read rather than scored.
 * - **No em dash and no filler**, the same rule `copy.test.ts` applies to every
 *   other authored string in core.
 * - **One idea per field.** The note says how the word is used, not what it
 *   means; `en` already did that. The example is one sentence somebody would
 *   actually say, not a sentence built to contain the word.
 *
 * Growing the pool re-phases the daily sequence, which is accepted: the
 * alternative is storing today's pick, and a stored derived value is a second
 * source of truth about a day.
 */

export interface DailyWord {
  /** Stable id, e.g. 'word:bonjour'. Never reused, never renumbered. */
  id: string;
  /** The French word or short phrase, as a learner would meet it. */
  fr: string;
  /** The plain English meaning. */
  en: string;
  /** One short sentence on how it is actually used. */
  note: string;
  /** One natural French example sentence using it. */
  exampleFr: string;
  /** That sentence in English. */
  exampleEn: string;
}

