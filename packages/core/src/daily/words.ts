/**
 * The word of the day pool.
 *
 * Home opens on one French word, and which word it is comes from `dailyPick`.
 * That means this file is the whole content surface: there is no generator, no
 * model call and no stored choice, so a word a learner meets on a Tuesday is a
 * word somebody wrote on purpose.
 *
 * ## The bar
 *
 * The founder read the first version of this pool and said the quiet part out
 * loud: `bonjour` is not a word of the day, because everybody already knows it.
 * A card that spends a learner's one daily reading on a word they had before
 * they installed anything is a card that taught nothing, however well it was
 * drawn. So every entry here has to clear one bar:
 *
 * > If a phrasebook's first page covers it, it does not belong on this card.
 *
 * `daily.test.ts` holds that bar as `PHRASEBOOK_FIRST_PAGE` and refuses any
 * `fr` on the list. The list is not the whole rule and cannot be: it names the
 * words a phrasebook opens with, and the judgement about the rest lives with
 * whoever adds an entry. What the list does is make the failure loud when the
 * judgement slips.
 *
 * ## The three tiers
 *
 * The bar alone would give one flat pool of hard words, which is the other way
 * to waste the card: a beginner meeting `le dépaysement` on day three learns a
 * beautiful word they cannot use. So the pool is tiered, and `tier.ts` maps the
 * learner's level standing onto it.
 *
 * - **Tier one** is the French of week two rather than day one, and it is used
 *   the same afternoon: `un pourboire`, `la queue`, `en panne`, `un apéro`.
 *   Nothing here is obvious, and everything here is immediately spendable.
 * - **Tier two** is what French people actually say and what textbooks skip:
 *   `en fait`, `la flemme`, `bosser`, `être crevé`. The register a learner
 *   needs in order to stop sounding like a written exercise.
 * - **Tier three** is the vocabulary that makes a French speaker look up:
 *   `le dépaysement`, `flâner`, `les retrouvailles`, `un coup de foudre`.
 *   Words with no clean English, and idioms carrying an image.
 *
 * A tier is a pitch, not a claim. Being shown a tier three word says nothing
 * about whether a learner knows it, and nothing in this file is evidence of
 * anything: reading a card is not production, and the ladder is fed by what a
 * learner says, never by what the app displayed at them.
 *
 * ## Rules that hold the pool together
 *
 * Four of them, and three are enforced by `daily.test.ts` rather than by good
 * intentions:
 *
 * - **Ids are permanent.** They are never reused and never renumbered, because
 *   a bookmark saved into My French points at one, and re-pointing it would
 *   quietly change what a learner saved. When the pool was rewritten above the
 *   bar, the eight words that already cleared it kept their ids and the rest
 *   retired; no retired id is ever handed to a different word.
 * - **No digits anywhere a learner reads.** A number on this card is either a
 *   price that is already wrong or a count that means nothing, and PEDAGOGY.md
 *   keeps counts off the surfaces meant to be read rather than scored.
 * - **No em dash and no filler**, the same rule `copy.test.ts` applies to every
 *   other authored string in core.
 * - **One idea per field.** The note says how the word is used, not what it
 *   means; `en` already did that. The example is one sentence somebody would
 *   actually say, not a sentence built to contain the word.
 *
 * The English fields carry one more rule that is enforced from the app side, in
 * `apps/mobile/src/copy/dailyPools.test.ts`: Luvani's ban list, matched by
 * substring. It catches ordinary words on purpose, which is why nothing here
 * says breakfast, closed, lost or a flower.
 *
 * Growing the pool re-phases the daily sequence, which is accepted: the
 * alternative is storing today's pick, and a stored derived value is a second
 * source of truth about a day.
 */

export interface DailyWord {
  /** Stable id, e.g. 'word:un-creme'. Never reused, never renumbered. */
  id: string;
  /** The French word or short phrase, as a learner would meet it. */
  fr: string;
  /** The plain English meaning. */
  en: string;
  /**
   * How far past the first page this one sits.
   *
   * One is week-two French that gets spent the same day, two is the spoken
   * register textbooks leave out, three is the vocabulary a French speaker
   * enjoys hearing a learner use. `wordTierFor` in `tier.ts` decides which
   * tier today's card is drawn from.
   */
  tier: 1 | 2 | 3;
  /** One short sentence on how it is actually used. */
  note: string;
  /** One natural French example sentence using it. */
  exampleFr: string;
  /** That sentence in English. */
  exampleEn: string;
}

