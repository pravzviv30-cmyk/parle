import assert from 'node:assert/strict';
import { test } from 'node:test';
import { ConversationTextBuffer, ConversationTextRecorder, isConversationText, isSavedConversationText } from './conversationText.ts';
import type { ConvoView, ServerMessage } from './protocol/protocol.ts';
const id = '11111111-1111-4111-8111-111111111111';
const line = { id: 't1', who: 'learner' as const, fr: 'Bonjour', frWritten: null, en: null };
test('optional saved text retains repeated real lines and all older turns without silent truncation', () => {
  const buffer = new ConversationTextBuffer();
  for (let i = 0; i < 80; i++) buffer.append({ ...line, id: `t${i}` });
  assert.equal(buffer.snapshot()?.length, 80);
  buffer.append({ ...line, id: 't79' });
  assert.equal(buffer.snapshot()?.length, 80, 'only the same event id is deduplicated');
  const copy = buffer.snapshot()!;
  copy[0]!.fr = 'changed copy';
  assert.equal(buffer.snapshot()![0]!.fr, 'Bonjour');
  buffer.remove('t0'); assert.equal(buffer.snapshot()?.length, 79);
  buffer.clear(); assert.deepEqual(buffer.snapshot(), []);
  for (let i = 0; i <= 500; i++) buffer.append({ ...line, id: `t${i}` });
  assert.equal(buffer.snapshot(), null, 'overflow cannot be sold as a full transcript');
});
test('saved-text validation rejects audio, foreign metadata, repeated ids and malformed rows', () => {
  const conversation = { sessionId: id, title: 'Au café', lines: [line] };
  assert.ok(isConversationText(conversation));
  assert.ok(isSavedConversationText({ ...conversation, savedAt: '2026-10-02T12:00:00Z' }));
  for (const invalid of [{ ...conversation, audio: 'secret' }, { ...conversation, userId: 'foreign' }, { ...conversation, lines: [line, line] }, { ...conversation, lines: [{ ...line, extra: 'secret' }] }, { ...conversation, lines: [] }, { ...conversation, sessionId: 'bad' }]) assert.equal(isConversationText(invalid), false);
  assert.equal(isSavedConversationText({ ...conversation, savedAt: 'bad' }), false);
  const buffer = new ConversationTextBuffer();
  for (let i = 0; i < 110; i++) buffer.append({ ...line, id: `t${i}`, fr: 'é'.repeat(1900) });
  assert.equal(buffer.snapshot(), null, 'UTF-8 byte budget is bounded too');
});

test('saved text distinguishes repeated real replies from ready replay and support-only updates', () => {
  const recorder = new ConversationTextRecorder();
  const view: ConvoView = { textTurnId: 'v1', sceneReply: { speaker: 'Waiter', fr: 'Bonjour', frWritten: null, en: 'Hello' }, coachLine: null, coachNow: [], narration: null, supportView: { kind: 'none' }, rung: 4, beat: { goalEn: 'Order', position: 1, total: 2 }, recapDue: false, missionDone: false };
  const finish = { t: 'recap', recap: {}, profile: {} } as unknown as ServerMessage;
  recorder.receive({ t: 'convo', view });
  recorder.receive({ t: 'transcript', text: 'Bonjour', final: true });
  recorder.receive({ t: 'convo', view });
  recorder.receive({ t: 'convo', view: { ...view, supportView: { kind: 'hint', hint: 'Greet the waiter' } } });
  recorder.receive({ t: 'convo', view: { ...view, textTurnId: 'v2' } });
  assert.equal(recorder.snapshot(), null, 'no save before a recap');
  recorder.receive(finish);
  assert.deepEqual(recorder.snapshot()?.map(line => line.who), ['tutor', 'learner', 'tutor']);
  recorder.receive({ t: 'transcript', text: 'late', final: true });
  assert.equal(recorder.snapshot()?.length, 3);
  recorder.receive({ t: 'safety', category: 'under-13', action: 'stop', message: 'This session has ended.' });
  assert.equal(recorder.snapshot(), null, 'a late safety stop also discards an already prepared text');
  recorder.clear();
  recorder.receive({ t: 'transcript', text: 'old', final: true });
  recorder.receive({ t: 'safety', category: 'under-13', action: 'stop', message: 'This session has ended.' });
  recorder.receive(finish);
  assert.equal(recorder.snapshot(), null);
  recorder.clear();
  const { textTurnId: ignored, ...oldView } = view;
  recorder.receive({ t: 'convo', view: oldView }); recorder.receive(finish);
  assert.equal(recorder.snapshot(), null, 'old agent replay ambiguity cannot become a supposedly full saved transcript');
  recorder.clear();
  recorder.receive({ t: 'convo', view: { ...view, coachLine: 'Try saying bonjour first.', coachNow: [{ kind: 'recast', quote: 'une café', better: 'un café', betterWritten: null, betterEn: 'a coffee', why: 'Café is masculine.', weight: 'matters-now' }] } });
  recorder.receive(finish);
  assert.deepEqual(recorder.snapshot()?.map(line => line.who), ['tutor', 'coach', 'coach']);
  assert.match(recorder.snapshot()![2]!.fr, /une café.*un café/);
  assert.match(recorder.snapshot()![2]!.fr, /Café is masculine/);
});
